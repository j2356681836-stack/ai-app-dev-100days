# 订单字段定义
# 1. 定义品牌枚举范围
class BrandEnum(str, Enum):
    Lancome = "兰蔻"
    EsteeLauder = "雅诗兰黛"
    SKII = "SK-II"
    LaMer = "海蓝之谜"
    HR = "赫莲娜"
    Others = "其他品牌"

# 2. 订单明细
class OrderItems(BaseModel):
    brand_name: BrandEnum = Field(description = "品牌名，不在枚举的具体品牌名字一律放进'其他品牌'中")
    product_name: str = Field(description = '属于该品牌的商品名')
    price: int = Field(description = '商品单价')
    quantity: int = Field(description = '商品购买数量')
    sku_code: int = Field(description="必须输出一个纯数字的商品编码，如果原文没有，必须生成 9999")

class UserSentiment(BaseModel):
    is_angry: bool
    reason: str = Field(description = "简述对商品不满意的原因")

class BeautyOrder(BaseModel):
    items: list[OrderItems]
    total_amount: int
    discount_applied: bool 

    @model_validator(mode = 'after')
    # 折扣验证
    def check_amount(self) -> "BeautyOrder":
        # 计算订单明细总价
        ttl_amount = sum(item.price * item.quantity for item in self.items)
        # 情况1：没有打折
        # 订单总价等于明细总和
        if not self.discount_applied and ttl_amount != self.total_amount:
            raise ValueError(f"订单未打折，明细总和{ttl_amount}不等于订单实付金额{self.total_amount}。")
        # 情况2：订单有折扣
        # 实付金额应小于订单明细总和
        if self.discount_applied and self.total_amount >= ttl_amount:
            raise ValueError(f"折扣后的实付金额{self.total_amount}高于订单明细总和{ttl_amount}。")
        # 除以上情况外，验证通过
        return self

    # 获取核心品牌的订单
    def get_core_brand(self):
        core_items = [item for item in self.items if item.brand_name != BrandEnum.Others]
        core_revenue = sum(item.price * item.quantity for item in core_items)
        return {
            "core_items": core_items,
            "core_revenue": core_revenue
        }

# 异步并发
# 1. 定义全局锁
file_lock = asyncio.Lock()
# 异步写入函数
async def save_to_jsonl(data:dict, file_path:str):
    # 在写入磁盘的上下文加锁
    async with file_lock:
        # 使用追加模式
        async with aiofiles.open(file_path, mode = "a", encoding = "utf-8") as f:
            # 转换为json字符
            json_str = json.dumps(data, ensure_ascii = False)
            await f.write(json_str + "\n")

# Langfuse观测
@observe()
# =========================
# 1. 网络层 retry
# =========================

# Tenacity装饰器：只负责网络retry(timeout/rate limit/connection error)不处理schema错误
@retry(
    retry = retry_if_exception_type(
        (
            APIConnectionError,
            APITimeoutError,
            RateLimitError,
        )
    ),
    wait = wait_exponential(multiplier=1, min=2, max=10),   # 指数退避
    stop = stop_after_attempt(5)    #最多重试5次
    )

async def call_openai(messages, response_model):

    response = await client.responses.parse(
        model = "gpt-5.4-mini",
        input = messages,
        text_format = response_model,
    )

    return response

# =========================
# 2. Structured Output
# =========================

async def generate_structured_output(
    *,      # 后面的参数必须“显式写参数名”
    system_prompt: str,
    user_text: str,
    response_model: Type[T],    # basemodel占位符
    sem: asyncio.Semaphore,
    max_repair_attempts: int = 3,
):

    base_messages = [
        {
            "role": "system",
            "content": system_prompt,
        },
        {
            "role": "user",
            "content": user_text,
        },
    ]

    repair_message = None

    for attempt in range(max_repair_attempts):
        messages = base_messages.copy()

        # 只追加最新一次repair
        if repair_message:      
            messages.append(repair_message)

        try:
            async with sem:
                response = await call_openai(
                    messages = messages,
                    response_model = response_model,
                )
            print(f"✅ Structured generation success")

            return response.output_parsed

        # =========================
        # schema修复
        # =========================

        except ValidationError as e:
            errors = e.errors()
            print(f"❌ Schema validation failed")

            # 将错误原因追加到大模型的上下文中retry
            # 模型对英文 schema repair 更敏感,提高成功率
            repair_message = {
                "role": "user",
                "content": f"""
Your previous output failed schema validation.

Validation errors:

{errors}

Requirements:

1. Return valid JSON only
2. Do not omit required fields
3. Ensure all field types are correct
4. Follow the schema exactly
5. Do not include explanations

Regenerate the response.
""",
            }

        # =========================
        # 其他异常
        # =========================

        except Exception as e:
            print(f"❌ Unexpected error: {e}")
            raise 

    raise RuntimeError(
        f"Structured output failed after "
        f"{max_repair_attempts} repair attempts."
    )


