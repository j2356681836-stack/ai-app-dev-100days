# 业务逻辑：单条文本的异步函数
async def single_text(text:str, text_id:int, sem:asyncio.Semaphore):
    # 在函数内部建立上下文隔离区，注入业务标签
    with propagate_attributes(
        trace_name = "Beauty_Data_Pipeline",
        user_id = "user_330",
        session_id = "",
        tags = ["batch_day16", "sentiment_order_mixed"],
        metadata={"text_id": text_id} # 直接将本次的唯一ID打入元数据，方便控制台精准搜索
    ):

        # 双路（orders+sentiments)并发,拼装数据+加锁落盘
        # 1. 双路并发
        task_order = generate_structured_output(
            system_prompt = '严格提取订单数据，认真对品牌进行归类。',
            user_text = text,
            response_model = BeautyOrder,
            sem = sem
        )

        task_sentiment = generate_structured_output(
            system_prompt = '分析用户的情绪，对产品是否满意。',
            user_text = text,
            response_model = UserSentiment,
            sem = sem
        )

        # 2. 结果返回
        # gather：打包
        results = await asyncio.gather(
            task_order,
            task_sentiment,
            return_exceptions = True    # 其中一个任务失败，另一个也正常运行
            )
        
        orders,sentiments = results

        if isinstance(orders, Exception):
            print("订单抽取失败")
            return 
        if isinstance(sentiments, Exception):
            print("情绪分析失败")
            return 

        # 3. 数据拼接
        all_data = {
            "text_id" : text_id,
            "original_text" : text[:15] + "...",
            "order_info" : orders.model_dump(),
            "sentiment_info" : sentiments.model_dump()
        }

        # 4. 落盘
        await save_to_jsonl(
            data = all_data,
            file_path = "day16_output.jsonl")

        print(f"数据{text_id}已流式落盘。")

# 异步代码控制台
async def main():
    print(f"---纯流式架构启动，共{len(order_texts)}条数据 ---")
    start_time= time.time()

    # 设置并发上限
    global_sem = asyncio.Semaphore(5)

    # 创建任务组
    tasks = []

    # enumerate()会把列表里的每一条数据自动打上一个从 0 开始的序号，变成一个类似“序号+内容”的组合
    for i,text in enumerate(order_texts):
        # 创建协程对象
        tasks.append(single_text(text, text_id=i, sem = global_sem))

    await asyncio.gather(*tasks)

    end_time = time.time() # 记录结束时间
    print(f"\n API 请求总耗时: {end_time - start_time:.2f} 秒")
    print("数据写入完成")


if __name__ == "__main__":
    # 启动
    asyncio.run(main())







